const languageButtons = document.querySelectorAll("[data-language]");
const experienceList = document.querySelector("#experience-list");
const stackGrid = document.querySelector("#stack-grid");

function renderList(list, className) {
  return list
    .map(
      (item) => `
    <article class="${className}">
      <div class="experience-period">${item.period}</div>
      <div>
        <div class="experience-company">${item.company}</div>
        <h3 class="experience-title">${item.title}</h3>
        <p class="experience-description">${item.description}</p>
        <ul class="experience-highlights">
          ${item.highlights.map((highlight) => `<li>${highlight}</li>`).join("")}
        </ul>
      </div>
    </article>
  `,
    )
    .join("");
}

function renderStack(items) {
  return items
    .map(
      (item) => `
    <article class="stack-item">
      <h3>${item.title}</h3>
      <p>${item.items}</p>
    </article>
  `,
    )
    .join("");
}

function setLanguage(language) {
  const translation = content[language];
  if (!translation) return;

  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translation[key]) element.textContent = translation[key];
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (translation[key]) element.alt = translation[key];
  });
  experienceList.innerHTML = renderList(
    translation.experience,
    "experience-item",
  );
  stackGrid.innerHTML = renderStack(translation.stack);
  languageButtons.forEach((button) => {
    button.setAttribute(
      "aria-pressed",
      String(button.dataset.language === language),
    );
  });
  document.title = `${language === "ru" ? "Александр Пылаев" : "Aleksandr Pylaev"} — ${translation.heroTitle}`;
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

setLanguage("en");
